/**
 * Audited figures (the year-end true-up; finance-books.md
 * "Audited figures"). Once a year has ended and the CA has signed its
 * statements, the treasurer (`finance.adjust`) enters the audited balance
 * sheet; this posts the differences as one balanced posting dated the
 * year's last day, so the year's closing, and the next year's opening,
 * equal the audited figures line for line. The rules are the pure
 * `planAuditedFigures` (`@pi-dash/shared/audited-figures`); here the
 * server reads the books itself, refuses figures entered against books
 * that have since changed, and writes the document with its lines. A
 * correction reverses the whole document and enters a new one; a year can
 * also be marked as skipped, with a reason, for the year-close checklist.
 */

export interface AuditedFiguresInput {
  added?: readonly AddedLineInput[];
  caName: string;
  fiscalYearId: string;
  /** Generated by the form, so a double submit posts once. */
  id: string;
  /** Every line the form showed, with what it showed as in the books. */
  lines: readonly {
    auditedPaise: number;
    booksPaise: number;
    counterHeadId?: string | null;
    key: string;
  }[];
  signedOn: string;
  transfers?: readonly FundTransferInput[];
}

type YearRow = typeof fiscalYear.$inferSelect;

async function lockYearDocument(tx: LedgerTx, fiscalYearId: string) {
  await tx.execute(
    sql`SELECT pg_advisory_xact_lock(hashtextextended(${`ledger:audited_figures_year:${fiscalYearId}`}, 0))`
  );
  // FOR NO KEY UPDATE conflicts with the engine's FOR SHARE on the year:
  // a posting into the year waits for this document's transaction, then
  // sees the match (and is refused), so no posting lands between reading
  // the books and writing the document.
  const [year] = await tx
    .select()
    .from(fiscalYear)
    .where(eq(fiscalYear.id, fiscalYearId))
    .for("no key update")
    .limit(1);
  if (!year) {
    throw new LedgerError("not_found", "That financial year doesn't exist");
  }
  return year;
}

/**
 * The years are matched in order: the previous ended books year must be
 * matched or skipped before the next one is entered.
 */
async function assertPreviousYearDone(tx: LedgerTx, year: YearRow) {
  const [previous] = await tx
    .select()
    .from(fiscalYear)
    .where(
      and(
        lt(fiscalYear.startsOn, year.startsOn),
        gte(fiscalYear.endsOn, LEDGER_CUTOVER_ON)
      )
    )
    .orderBy(desc(fiscalYear.startsOn))
    .limit(1);
  if (previous && !(await standingDocument(tx, previous.id))) {
    throw new LedgerError(
      "invalid",
      `Match or skip FY ${previous.label}'s audited figures first: each year opens from the one before`
    );
  }
}

/** A later year's matched figures were checked against this year's closing. */
async function assertNoLaterMatch(tx: LedgerTx, year: YearRow) {
  const [later] = await tx
    .select({ label: fiscalYear.label })
    .from(auditedFigures)
    .innerJoin(fiscalYear, eq(fiscalYear.id, auditedFigures.fiscalYearId))
    .where(
      and(
        gt(fiscalYear.startsOn, year.startsOn),
        eq(auditedFigures.status, "matched"),
        isNull(auditedFigures.reversedAt)
      )
    )
    .orderBy(fiscalYear.startsOn)
    .limit(1);
  if (later) {
    throw new LedgerError(
      "invalid",
      `Reverse FY ${later.label}'s audited figures first: they were matched against this year's closing`
    );
  }
}

/**
 * Records dated in the year still waiting to post (or never looked at)
 * would change the closing after the match, so the match waits for them.
 */
async function assertNothingWaiting(tx: LedgerTx, year: YearRow) {
  const range = { endsOn: year.endsOn, startsOn: year.startsOn };
  const waiting = await waitingByReason(tx, range);
  const unchecked = await uncheckedSources(tx, range);
  const count =
    [...waiting.values()].reduce((sum, n) => sum + n, 0) + unchecked;
  if (count > 0) {
    throw new LedgerError(
      "invalid",
      `${count === 1 ? "1 record" : `${count} records`} dated in FY ${year.label} ${count === 1 ? "is" : "are"} waiting to post. Post them, or resolve why they wait (Books → Waiting to post), before matching the audited figures.`
    );
  }
}

/** The year is in the books and has ended. */
function assertEnded(year: YearRow, now: Date) {
  if (year.endsOn < LEDGER_CUTOVER_ON) {
    throw new LedgerError(
      "invalid",
      `The books start on ${LEDGER_CUTOVER_ON}: FY ${year.label}'s audited figures are already the opening balances`
    );
  }
  if (todayInKolkata(now) <= year.endsOn) {
    throw new LedgerError(
      "invalid",
      `FY ${year.label} hasn't ended yet: its audited figures are matched after ${year.endsOn}, once the CA has signed the statements`
    );
  }
}

async function standingDocument(tx: LedgerTx, fiscalYearId: string) {
  const [live] = await tx
    .select()
    .from(auditedFigures)
    .where(
      and(
        eq(auditedFigures.fiscalYearId, fiscalYearId),
        isNull(auditedFigures.reversedAt)
      )
    )
    .limit(1);
  return live ?? null;
}

function assertNoStanding(
  live: typeof auditedFigures.$inferSelect | null,
  year: YearRow
) {
  if (live) {
    throw new LedgerError(
      "invalid",
      live.status === "skipped"
        ? `FY ${year.label}'s audited figures are marked as skipped. Reverse that to enter them.`
        : `FY ${year.label}'s audited figures are already matched. Reverse them to enter a correction.`
    );
  }
}

/** Accounts the books list: active non-cash ones, and any account that has moved. */
async function bookAccountIds(tx: LedgerTx): Promise<string[]> {
  const rows = await tx
    .select({ id: orgAccount.id })
    .from(orgAccount)
    .where(
      or(
        and(eq(orgAccount.active, true), sql`${orgAccount.kind} <> 'cash'`),
        sql`exists (select 1 from ${accountMovement} where ${accountMovement.orgAccountId} = ${orgAccount.id})`
      )
    )
    .orderBy(orgAccount.name, orgAccount.id);
  return rows.map((r) => r.id);
}

/**
 * Every balance sheet line the books hold at the end of `asOf`, as the
 * Audited figures page lists them, with each line's name for the memos.
 */
export async function loadBalanceSheetLines(
  tx: LedgerTx,
  asOf: string
): Promise<{
  labelOf: (line: BalanceSheetLine) => string;
  lines: BalanceSheetLine[];
}> {
  // One after another: a transaction runs one statement at a time.
  const accountIds = await bookAccountIds(tx);
  const funds = await tx
    .select({ active: fund.active, id: fund.id, name: fund.name })
    .from(fund)
    .orderBy(fund.name);
  const heads = await tx
    .select({ id: accountHead.id, name: accountHead.name })
    .from(accountHead);
  // Summed in SQL by everything a line depends on (head, fund, effect, and
  // a fixed asset's name), so a year's closing reads a few rows per head
  // rather than every entry since the cutover.
  // Inlined constants, not parameters: GROUP BY must repeat the select's
  // expression exactly.
  const assetSources = sql.raw(
    ASSET_LINE_SOURCE_TYPES.map((t) => `'${t}'`).join(", ")
  );
  const assetMemo = sql<string | null>`case when ${accountHead.type} = 'asset'
    and ${posting.sourceType} in (${assetSources}) then ${ledgerEntry.memo} end`;
  const entries = await tx
    .select({
      accountHeadId: ledgerEntry.accountHeadId,
      amountPaise: sql<number>`sum(${ledgerEntry.amountPaise})`.mapWith(Number),
      effect: ledgerEntry.effect,
      fundId: ledgerEntry.fundId,
      headType: accountHead.type,
      memo: assetMemo,
      sourceType: posting.sourceType,
    })
    .from(ledgerEntry)
    .innerJoin(posting, eq(posting.id, ledgerEntry.postingId))
    .innerJoin(accountHead, eq(accountHead.id, ledgerEntry.accountHeadId))
    .where(lte(ledgerEntry.economicOn, asOf))
    .groupBy(
      ledgerEntry.accountHeadId,
      accountHead.type,
      ledgerEntry.fundId,
      ledgerEntry.effect,
      posting.sourceType,
      assetMemo
    );
  const movements = await tx
    .select({
      amountPaise: sql<number>`sum(${accountMovement.amountPaise})`.mapWith(
        Number
      ),
      direction: accountMovement.direction,
      orgAccountId: accountMovement.orgAccountId,
    })
    .from(accountMovement)
    .where(lte(accountMovement.occurredOn, asOf))
    .groupBy(accountMovement.orgAccountId, accountMovement.direction);
  const lines = balanceSheetLines({
    accountIds,
    asOf,
    entries: entries.map((e) => ({
      ...e,
      economicOn: asOf,
      headType: e.headType as BookHeadType,
    })),
    fundIds: funds.filter((f) => f.active).map((f) => f.id),
    movements: movements.map((m) => ({
      ...m,
      id: `${m.orgAccountId}:${m.direction}`,
      occurredOn: asOf,
    })),
  });
  const headNames = new Map(heads.map((h) => [h.id, h.name]));
  const fundNames = new Map(funds.map((f) => [f.id, f.name]));
  const labelOf = (line: BalanceSheetLine) => {
    if (line.kind === "fund") {
      return fundNames.get(line.fundId ?? "") ?? "Fund";
    }
    return (
      line.memo ?? headNames.get(line.accountHeadId ?? "") ?? "Account head"
    );
  };
  return { labelOf, lines };
}

/** The heads the audited figures post under must exist with their types. */
async function assertReferenceData(tx: LedgerTx) {
  const required = [
    { id: LEDGER_ACCOUNT_HEAD_IDS.depreciation, type: "expense" },
    { id: LEDGER_ACCOUNT_HEAD_IDS.yearEndAdjustments, type: "expense" },
    { id: LEDGER_ACCOUNT_HEAD_IDS.yearEndAdjustmentsIncome, type: "income" },
    { id: LEDGER_ACCOUNT_HEAD_IDS.fundTransfers, type: "fund" },
  ];
  const rows = await tx
    .select({ id: accountHead.id, type: accountHead.type })
    .from(accountHead)
    .where(
      inArray(
        accountHead.id,
        required.map((r) => r.id)
      )
    );
  const typeById = new Map(rows.map((r) => [r.id, r.type]));
  if (required.some((r) => typeById.get(r.id) !== r.type)) {
    throw new LedgerError(
      "invalid",
      "Books reference data missing: the Depreciation, Year-end adjustments (audited), Year-end adjustments (audited) — income or Transfers between funds account head couldn't be created. Ask an administrator to check the server log.",
      { fault: true }
    );
  }
}

/** Active income and expense heads, the ones a difference may post against. */
async function counterHeads(
  tx: LedgerTx
): Promise<Map<string, CounterHeadType>> {
  const rows = await tx
    .select({ id: accountHead.id, type: accountHead.type })
    .from(accountHead)
    .where(
      and(
        eq(accountHead.active, true),
        inArray(accountHead.type, ["income", "expense"])
      )
    );
  return new Map(rows.map((r) => [r.id, r.type as CounterHeadType]));
}

async function assertAddedHeads(
  tx: LedgerTx,
  added: readonly AddedLineInput[]
) {
  if (added.length === 0) {
    return;
  }
  const rows = await tx
    .select({
      active: accountHead.active,
      id: accountHead.id,
      type: accountHead.type,
    })
    .from(accountHead)
    .where(
      inArray(
        accountHead.id,
        added.map((a) => a.accountHeadId)
      )
    );
  const byId = new Map(rows.map((r) => [r.id, r]));
  for (const line of added) {
    const head = byId.get(line.accountHeadId);
    if (!(head?.active && head.type === line.kind)) {
      throw new LedgerError(
        "invalid",
        `Pick an active ${line.kind === "asset" ? "asset" : "liability"} head for each added line`
      );
    }
  }
}

const BOOKS_CHANGED =
  "The books changed since the page was opened. Check the figures against the books again, then post.";

function assertCaFields(
  input: Pick<AuditedFiguresInput, "caName" | "signedOn">,
  year: YearRow,
  now: Date
) {
  if (!input.caName.trim()) {
    throw new LedgerError("invalid", "Enter the chartered accountant's name");
  }
  if (!isIsoDay(input.signedOn)) {
    throw new LedgerError(
      "invalid_date",
      "Enter the date the CA signed the statements"
    );
  }
  if (input.signedOn > todayInKolkata(now)) {
    throw new LedgerError(
      "invalid_date",
      "The signing date can't be in the future"
    );
  }
  if (input.signedOn <= year.endsOn) {
    throw new LedgerError(
      "invalid_date",
      `The statements are signed after the year ends (${year.endsOn})`
    );
  }
}

/** Writes the document, its posting and its lines; a repeat of the same id returns it. */
export async function postAuditedFigures(
  tx: LedgerTx,
  input: AuditedFiguresInput,
  context: { actorId: string; now?: Date }
) {
  const now = context.now ?? new Date();
  const year = await lockYearDocument(tx, input.fiscalYearId);
  const [existing] = await tx
    .select()
    .from(auditedFigures)
    .where(eq(auditedFigures.id, input.id))
    .limit(1);
  if (existing) {
    return existing;
  }
  assertEnded(year, now);
  if (year.closedAt) {
    throw new LedgerError(
      "closed_year",
      `Reopen FY ${year.label} to match its audited figures`
    );
  }
  assertCaFields(input, year, now);
  assertNoStanding(await standingDocument(tx, year.id), year);
  await assertPreviousYearDone(tx, year);
  await assertNothingWaiting(tx, year);
  const [opening] = await tx
    .select({ id: openingBalance.id })
    .from(openingBalance)
    .innerJoin(fiscalYear, eq(fiscalYear.id, openingBalance.fiscalYearId))
    .where(
      and(
        eq(fiscalYear.startsOn, LEDGER_CUTOVER_ON),
        isNull(openingBalance.reversalPostingId)
      )
    )
    .limit(1);
  if (!opening) {
    throw new LedgerError(
      "invalid",
      "Post the opening balances first: the audited figures are matched against the books they start"
    );
  }
  await assertReferenceData(tx);

  const { labelOf, lines } = await loadBalanceSheetLines(tx, year.endsOn);
  const given = new Map(input.lines.map((l) => [l.key, l]));
  if (
    given.size !== input.lines.length ||
    given.size !== lines.length ||
    lines.some((l) => given.get(l.key)?.booksPaise !== l.booksPaise)
  ) {
    throw new LedgerError("invalid", BOOKS_CHANGED);
  }
  const added = input.added ?? [];
  await assertAddedHeads(tx, added);
  const transfers = input.transfers ?? [];
  const plan = planAuditedFigures({
    added,
    audited: input.lines.map((l) => ({
      auditedPaise: l.auditedPaise,
      counterHeadId: l.counterHeadId ?? null,
      key: l.key,
    })),
    books: lines,
    counterHeads: await counterHeads(tx),
    labelOf,
    transfers,
  });
  const [blocker] = plan.blockers;
  if (blocker) {
    throw new LedgerError(
      blocker.code === "audited_unbalanced" ? "unbalanced" : "invalid",
      blocker.message
    );
  }

  let postingId: string | null = null;
  if (plan.entries.length > 0) {
    const { posting: written } = await post(
      tx,
      {
        action: POSTING_ACTIONS.post,
        economicOn: year.endsOn,
        entries: plan.entries,
        movements: [],
        sourceId: input.id,
        sourceType: LEDGER_SOURCE_TYPES.auditedFigures,
      },
      { actorId: context.actorId, now }
    );
    postingId = written.id;
  }
  const [document] = await tx
    .insert(auditedFigures)
    .values({
      asOn: year.endsOn,
      caName: input.caName.trim(),
      createdAt: now,
      createdBy: context.actorId,
      fiscalYearId: year.id,
      id: input.id,
      postingId,
      signedOn: input.signedOn,
      status: "matched",
    })
    .returning();
  if (!document) {
    throw new Error("Audited figures were not written");
  }
  const rows: (typeof auditedFiguresLine.$inferInsert)[] = plan.lines.map(
    (line, position) => ({
      accountHeadId: line.accountHeadId,
      added: line.added,
      auditedFiguresId: document.id,
      auditedPaise: line.auditedPaise ?? 0,
      booksPaise: line.booksPaise,
      counterHeadId: line.counterHead?.id ?? null,
      fundId: line.fundId,
      id: uuidv7(),
      kind: line.kind,
      lineKey: line.key,
      memo: line.memo,
      orgAccountId: line.orgAccountId,
      position,
    })
  );
  for (const transfer of transfers) {
    rows.push({
      added: false,
      auditedFiguresId: document.id,
      auditedPaise: transfer.amountPaise,
      booksPaise: 0,
      fundId: transfer.fromFundId,
      id: uuidv7(),
      kind: "fund_transfer",
      lineKey: `transfer:${transfer.fromFundId}:${transfer.toFundId}`,
      memo: transfer.reason.trim(),
      position: rows.length,
      toFundId: transfer.toFundId,
    });
  }
  await tx.insert(auditedFiguresLine).values(rows);
  return document;
}

function assertReason(reason: string, what: string): string {
  const trimmed = reason.trim();
  if (
    trimmed.length < AUDITED_REASON_MIN ||
    trimmed.length > AUDITED_REASON_MAX
  ) {
    throw new LedgerError("invalid", `Say why ${what}`);
  }
  return trimmed;
}

/**
 * Marks an ended year's audited figures as skipped, with the reason, so the
 * year-close checklist shows a decision rather than a gap. Posts nothing.
 */
export async function skipAuditedFigures(
  tx: LedgerTx,
  input: { fiscalYearId: string; id: string; reason: string },
  context: { actorId: string; now?: Date }
) {
  const now = context.now ?? new Date();
  const reason = assertReason(input.reason, "the audited figures are skipped");
  const year = await lockYearDocument(tx, input.fiscalYearId);
  const [existing] = await tx
    .select()
    .from(auditedFigures)
    .where(eq(auditedFigures.id, input.id))
    .limit(1);
  if (existing) {
    return existing;
  }
  assertEnded(year, now);
  assertNoStanding(await standingDocument(tx, year.id), year);
  await assertPreviousYearDone(tx, year);
  const [document] = await tx
    .insert(auditedFigures)
    .values({
      asOn: year.endsOn,
      createdAt: now,
      createdBy: context.actorId,
      fiscalYearId: year.id,
      id: input.id,
      skipReason: reason,
      status: "skipped",
    })
    .returning();
  if (!document) {
    throw new Error("Audited figures were not written");
  }
  return document;
}

/**
 * Reverses a standing document (its posting too, when it posted) so a
 * corrected one can be entered. The year must be open when it posted.
 */
export async function reverseAuditedFigures(
  tx: LedgerTx,
  input: { id: string; reason: string },
  context: { actorId: string; now?: Date }
) {
  const reason = assertReason(input.reason, "the audited figures are reversed");
  const [found] = await tx
    .select({ fiscalYearId: auditedFigures.fiscalYearId })
    .from(auditedFigures)
    .where(eq(auditedFigures.id, input.id))
    .limit(1);
  if (!found) {
    throw new LedgerError("not_found", "Those audited figures don't exist");
  }
  const year = await lockYearDocument(tx, found.fiscalYearId);
  const [document] = await tx
    .select()
    .from(auditedFigures)
    .where(eq(auditedFigures.id, input.id))
    .for("update")
    .limit(1);
  if (!document) {
    throw new LedgerError("not_found", "Those audited figures don't exist");
  }
  if (document.reversedAt) {
    throw new LedgerError(
      "already_reversed",
      "These audited figures are already reversed"
    );
  }
  await assertNoLaterMatch(tx, year);
  const now = context.now ?? new Date();
  let reversalPostingId: string | null = null;
  if (document.postingId) {
    if (year.closedAt) {
      throw new LedgerError(
        "closed_year",
        `Reopen FY ${year.label} to correct its audited figures`
      );
    }
    // The one posting allowed into a matched year: the match's own reversal.
    const { posting: reversal } = await reverse(tx, document.postingId, {
      actorId: context.actorId,
      intoMatchedYear: true,
      now,
      reason,
    });
    reversalPostingId = reversal.id;
  }
  await tx
    .update(auditedFigures)
    .set({
      reversalPostingId,
      reversalReason: reason,
      reversedAt: now,
      reversedBy: context.actorId,
    })
    .where(eq(auditedFigures.id, document.id));
  return { ...document, reversalPostingId, reversedAt: now };
}
