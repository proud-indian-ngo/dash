/**
 * Opening balances (finance-ledger-cutover.md section 2): one document per
 * year, posted once from the CA-confirmed figures the treasurer enters.
 * Money in the trust's accounts becomes opening movements in the cash book;
 * fixed assets, liabilities and fund balances become opening recognition
 * entries under asset, liability and fund heads. It posts only when assets
 * equal funds plus liabilities. A correction reverses the whole document
 * and posts a new one.
 */

export interface OpeningLineInput {
  /** asset and liability lines: the head (defaults: fixed assets, audit fees payable). */
  accountHeadId?: string | null;
  amountPaise: number;
  /** fund lines */
  fundId?: string | null;
  kind: OpeningLineKind;
  /** What the line is, such as the asset's name. */
  memo?: string | null;
  /** account lines */
  orgAccountId?: string | null;
}

export interface OpeningBalanceInput {
  caConfirmedOn: string;
  caName: string;
  fiscalYearId: string;
  /** Generated by the form, so a double submit posts once. */
  id: string;
  lines: readonly OpeningLineInput[];
}

const DEFAULT_HEAD: Record<"asset" | "liability", string> = {
  asset: LEDGER_ACCOUNT_HEAD_IDS.fixedAssets,
  liability: LEDGER_ACCOUNT_HEAD_IDS.auditFeesPayable,
};

function headOf(line: OpeningLineInput): string {
  if (line.kind === "asset" || line.kind === "liability") {
    return line.accountHeadId || DEFAULT_HEAD[line.kind];
  }
  return LEDGER_ACCOUNT_HEAD_IDS.fundBalance;
}

/**
 * The posting an opening-balance document makes, refused unless every line
 * is complete, each account and fund appears once, and it balances.
 */
export function buildOpeningPosting(
  input: Pick<OpeningBalanceInput, "id" | "lines">,
  asOn: string
): PostingInput {
  const accounts = new Set<string>();
  const funds = new Set<string>();
  const entries: EntryInput[] = [];
  const movements: MovementInput[] = [];
  for (const line of input.lines) {
    const memo = line.memo?.trim() || null;
    if (line.kind === "account") {
      if (!line.orgAccountId || accounts.has(line.orgAccountId)) {
        throw new LedgerError(
          "invalid",
          "Each account's opening balance is entered once"
        );
      }
      accounts.add(line.orgAccountId);
      movements.push({
        amountPaise: line.amountPaise,
        direction: "in",
        kind: "opening",
        memo,
        occurredOn: asOn,
        orgAccountId: line.orgAccountId,
      });
      continue;
    }
    if (line.kind === "fund") {
      if (!line.fundId || funds.has(line.fundId)) {
        throw new LedgerError(
          "invalid",
          "Each fund's opening balance is entered once"
        );
      }
      funds.add(line.fundId);
    }
    entries.push({
      accountHeadId: headOf(line),
      amountPaise: line.amountPaise,
      effect: "increase",
      // Assets and liabilities belong to the unrestricted general fund.
      fundId: line.kind === "fund" ? (line.fundId as string) : GENERAL_FUND_ID,
      memo,
    });
  }
  const check = openingBalanceCheck(input.lines);
  if (!check.balanced) {
    throw new LedgerError(
      "unbalanced",
      "The opening balances don't balance: assets must equal funds plus liabilities"
    );
  }
  return {
    action: POSTING_ACTIONS.post,
    economicOn: asOn,
    entries,
    movements,
    sourceId: input.id,
    sourceType: LEDGER_SOURCE_TYPES.openingBalance,
  };
}

async function assertReferences(
  tx: LedgerTx,
  lines: readonly OpeningLineInput[]
) {
  const accountIds = lines.flatMap((l) =>
    l.kind === "account" && l.orgAccountId ? [l.orgAccountId] : []
  );
  if (accountIds.length > 0) {
    const rows = await tx
      .select({ id: orgAccount.id })
      .from(orgAccount)
      .where(
        and(inArray(orgAccount.id, accountIds), eq(orgAccount.active, true))
      );
    if (rows.length !== new Set(accountIds).size) {
      throw new LedgerError("invalid", "Pick active organisation accounts");
    }
  }
  const fundIds = lines.flatMap((l) =>
    l.kind === "fund" && l.fundId ? [l.fundId] : []
  );
  if (fundIds.length > 0) {
    const rows = await tx
      .select({ id: fund.id })
      .from(fund)
      .where(inArray(fund.id, fundIds));
    if (rows.length !== new Set(fundIds).size) {
      throw new LedgerError("invalid", "Pick existing funds");
    }
  }
  const heads = lines.flatMap((l) =>
    l.kind === "asset" || l.kind === "liability"
      ? [{ id: headOf(l), kind: l.kind }]
      : []
  );
  if (heads.length > 0) {
    const rows = await tx
      .select({ id: accountHead.id, type: accountHead.type })
      .from(accountHead)
      .where(inArray(accountHead.id, [...new Set(heads.map((h) => h.id))]));
    const typeById = new Map(rows.map((r) => [r.id, r.type]));
    for (const head of heads) {
      if (typeById.get(head.id) !== head.kind) {
        throw new LedgerError(
          "invalid",
          `Pick an ${head.kind === "asset" ? "asset" : "a liability"} account head`
        );
      }
    }
  }
}

/** The heads opening lines post under must exist with their types. */
async function assertReferenceData(tx: LedgerTx) {
  const required = [
    { id: LEDGER_ACCOUNT_HEAD_IDS.fixedAssets, type: "asset" },
    { id: LEDGER_ACCOUNT_HEAD_IDS.auditFeesPayable, type: "liability" },
    { id: LEDGER_ACCOUNT_HEAD_IDS.fundBalance, type: "fund" },
  ];
  const rows = await tx
    .select({ id: accountHead.id, type: accountHead.type })
    .from(accountHead)
    .where(
      inArray(
        accountHead.id,
        required.map((r) => r.id)
      )
    );
  const typeById = new Map(rows.map((r) => [r.id, r.type]));
  if (required.some((r) => typeById.get(r.id) !== r.type)) {
    throw new LedgerError(
      "invalid",
      "Books reference data missing: the Fixed assets, Audit fees payable or Fund balance account head couldn't be created. Ask an administrator to check the server log.",
      { fault: true }
    );
  }
}

/** Writes the document and its posting; a repeat of the same id returns it. */
export async function postOpeningBalance(
  tx: LedgerTx,
  input: OpeningBalanceInput,
  context: { actorId: string; now?: Date }
) {
  const caName = input.caName.trim();
  if (!caName) {
    throw new LedgerError("invalid", "Enter the chartered accountant's name");
  }
  if (!isIsoDay(input.caConfirmedOn)) {
    throw new LedgerError("invalid_date", "Enter the date the CA confirmed");
  }
  if (input.caConfirmedOn > todayInKolkata(context.now ?? new Date())) {
    throw new LedgerError(
      "invalid_date",
      "The CA's confirmation date can't be in the future"
    );
  }
  // One opening-balance post per year at a time: a double submit waits and
  // then finds the first one; a second document finds the standing one.
  await tx.execute(
    sql`SELECT pg_advisory_xact_lock(hashtextextended(${`ledger:opening_balance_year:${input.fiscalYearId}`}, 0))`
  );
  const [year] = await tx
    .select()
    .from(fiscalYear)
    .where(eq(fiscalYear.id, input.fiscalYearId))
    .limit(1);
  if (!year) {
    throw new LedgerError("not_found", "That financial year doesn't exist");
  }
  if (year.startsOn !== LEDGER_CUTOVER_ON) {
    throw new LedgerError(
      "invalid",
      `Opening balances are entered once, for the year starting ${LEDGER_CUTOVER_ON}`
    );
  }
  const [existing] = await tx
    .select()
    .from(openingBalance)
    .where(eq(openingBalance.id, input.id))
    .limit(1);
  if (existing) {
    return existing;
  }
  const [live] = await tx
    .select({ id: openingBalance.id })
    .from(openingBalance)
    .where(
      and(
        eq(openingBalance.fiscalYearId, year.id),
        isNull(openingBalance.reversalPostingId)
      )
    )
    .limit(1);
  if (live) {
    throw new LedgerError(
      "invalid",
      `${year.label} already has opening balances. Reverse them to post a correction.`
    );
  }
  const postingInput = buildOpeningPosting(input, year.startsOn);
  await assertReferenceData(tx);
  await assertReferences(tx, input.lines);
  const { posting } = await post(tx, postingInput, {
    actorId: context.actorId,
    now: context.now,
  });
  const [row] = await tx
    .insert(openingBalance)
    .values({
      asOn: year.startsOn,
      caConfirmedOn: input.caConfirmedOn,
      caName,
      createdAt: context.now ?? new Date(),
      createdBy: context.actorId,
      fiscalYearId: year.id,
      id: input.id,
      postingId: posting.id,
    })
    .returning();
  if (!row) {
    throw new Error("Opening balance was not written");
  }
  return row;
}

/** Reverses a standing opening balance so a corrected one can be posted. */
export async function reverseOpeningBalance(
  tx: LedgerTx,
  input: { id: string; reason: string },
  context: { actorId: string; now?: Date }
) {
  const [document] = await tx
    .select()
    .from(openingBalance)
    .where(eq(openingBalance.id, input.id))
    .for("update")
    .limit(1);
  if (!document) {
    throw new LedgerError("not_found", "Those opening balances don't exist");
  }
  if (document.reversalPostingId) {
    throw new LedgerError(
      "already_reversed",
      "These opening balances are already reversed"
    );
  }
  const [matched] = await tx
    .select({ label: fiscalYear.label })
    .from(auditedFigures)
    .innerJoin(fiscalYear, eq(fiscalYear.id, auditedFigures.fiscalYearId))
    .where(
      and(
        eq(auditedFigures.status, "matched"),
        isNull(auditedFigures.reversedAt)
      )
    )
    .orderBy(fiscalYear.startsOn)
    .limit(1);
  if (matched) {
    throw new LedgerError(
      "invalid",
      `Reverse FY ${matched.label}'s audited figures first: they were matched against the books these opening balances start`
    );
  }
  const now = context.now ?? new Date();
  const { posting } = await reverse(tx, document.postingId, {
    actorId: context.actorId,
    now,
    reason: input.reason,
  });
  await tx
    .update(openingBalance)
    .set({
      reversalPostingId: posting.id,
      reversedAt: now,
      reversedBy: context.actorId,
    })
    .where(eq(openingBalance.id, document.id));
  return { ...document, reversalPostingId: posting.id };
}
