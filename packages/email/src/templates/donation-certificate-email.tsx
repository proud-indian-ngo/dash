import { EmailHeading, EmailLayout, EmailText } from "./email-layout";

export interface DonationCertificateEmailProps {
  appName?: string;
  appUrl?: string;
  donorName: string;
  /** "2026-27". */
  financialYear: string;
}

/** A donor's Form 114 certificate; the portal's PDF is attached. */
export default function DonationCertificateEmail({
  appName,
  appUrl,
  donorName,
  financialYear,
}: DonationCertificateEmailProps) {
  return (
    <EmailLayout
      appName={appName}
      appUrl={appUrl}
      preview={`Your Form 114 donation certificate for FY ${financialYear} from Proud Indian`}
    >
      <EmailHeading>Your donation certificate</EmailHeading>
      <EmailText>Dear {donorName},</EmailText>
      <EmailText>
        Thank you for supporting Proud Indian in FY {financialYear}. Your
        certificate of donation (Form 114, formerly Form 10BE), generated by the
        Income Tax Department from our donations statement, is attached to this
        email as a PDF.
      </EmailText>
      <EmailText>
        Please keep it for your income tax return. If any detail on it is wrong,
        reply to this email and we will correct it.
      </EmailText>
      <EmailText>With gratitude, Proud Indian</EmailText>
    </EmailLayout>
  );
}

DonationCertificateEmail.PreviewProps = {
  donorName: "Test Donor",
  financialYear: "2026-27",
} satisfies DonationCertificateEmailProps;
