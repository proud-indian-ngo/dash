import {
  GST_REGEX,
  IFSC_REGEX,
  PAN_REGEX,
} from "@pi-dash/zero/vendor-patterns";
import { isValidPhoneNumber } from "libphonenumber-js";
import z from "zod";

const text = (max: number) => z.string().trim().max(max);

/** Field rules without cross-field checks, so the form can pick and extend them. */
export const vendorFieldsSchema = z.object({
  address: text(500),
  bankAccountIfscCode: z
    .string()
    .trim()
    .toUpperCase()
    .min(1, "IFSC code is required")
    .regex(IFSC_REGEX, "Invalid IFSC code (e.g. SBIN0001234)"),
  bankAccountName: text(160).min(1, "Bank account name is required"),
  /** Blank keeps the stored account on update; a value replaces it. */
  bankAccountNumber: z.string().trim().max(34),
  contactEmail: z.union([z.literal(""), z.email("Invalid email address")]),
  contactPhone: z
    .string()
    .trim()
    .min(1, "Phone is required")
    .refine((v) => isValidPhoneNumber(v), "Invalid phone number"),
  /** The vendor row's updatedAt the editor loaded, so a stale save is refused; null on create. */
  expectedPartyUpdatedAt: z.number().int().nullable(),
  /** The private row's updatedAt the editor loaded; null when it had none. */
  expectedUpdatedAt: z.number().int().nullable(),
  gstNumber: z.union([
    z.literal(""),
    z
      .string()
      .trim()
      .toUpperCase()
      .regex(GST_REGEX, "Invalid GST number (e.g. 22AAAAA0000A1Z5)"),
  ]),
  /**
   * Generated by the form on create so a retried request is idempotent.
   * `guid` rather than `uuid`: fixtures use IDs without a version digit.
   */
  id: z.guid(),
  mode: z.enum(["create", "update"]),
  name: text(160).min(1, "Name is required"),
  /** Blank keeps a stored PAN; a value replaces it. */
  panNumber: z.union([
    z.literal(""),
    z
      .string()
      .trim()
      .toUpperCase()
      .regex(PAN_REGEX, "Invalid PAN (e.g. ABCDE1234F)"),
  ]),
});

export const accountNumberCheck = {
  check: (v: { bankAccountNumber: string; mode: "create" | "update" }) =>
    v.mode === "update" || v.bankAccountNumber.trim() !== "",
  message: "Account number is required",
};

/** Shared by the vendor form and the saveVendor server function. */
export const saveVendorSchema = vendorFieldsSchema.refine(
  accountNumberCheck.check,
  { message: accountNumberCheck.message, path: ["bankAccountNumber"] }
);

export type SaveVendorInput = z.infer<typeof saveVendorSchema>;
